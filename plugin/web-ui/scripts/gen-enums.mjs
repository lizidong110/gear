// 枚举产物生成器：把内核的「合法取值集合」从 Go 源码抽成 TS 常量。
//
// 为什么是「生成」而不是「手写 + 比对」：
// 红线 6（单一真相源）要求枚举只有一份定义。内核已经是真相源（model.go / cap.go），
// 前端再手写一份就是第二份真相——比对只能发现漂移，生成则根本不允许漂移。
// 这与内核既有的 `gofmt -l 零差异` 闸门同构：产物必须与源一致，否则 CI 红。
//
// 用法：
//   node scripts/gen-enums.mjs          # 生成 src/logic/generated/enums.ts
//   node scripts/check-contract.mjs     # 校验产物是否与 Go 源码一致（不改文件）

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
export const UI_ROOT = resolve(here, '..')
const REPO_ROOT = resolve(UI_ROOT, '..', '..')

export const MODEL_GO = resolve(REPO_ROOT, 'internal', 'model', 'model.go')
export const MODEL_VALIDATE_GO = resolve(REPO_ROOT, 'internal', 'model', 'validate.go')
export const CAP_GO = resolve(REPO_ROOT, 'internal', 'cap', 'cap.go')
export const OUT_FILE = resolve(UI_ROOT, 'src', 'logic', 'generated', 'enums.ts')

/** 枚举分布在多个源文件里（模型不变量在 model.go，状态机在 validate.go，原语在 cap.go）。 */
export const GO_SOURCES = [MODEL_GO, MODEL_VALIDATE_GO, CAP_GO]

/** 逐行剥掉 `//` 注释（跳过字符串内出现的 //），避免注释里的示例值污染解析。 */
export function stripComments(src) {
  return src
    .split('\n')
    .map((line) => {
      let quote = null
      for (let i = 0; i < line.length; i++) {
        const c = line[i]
        if (quote) {
          if (c === quote && line[i - 1] !== '\\') quote = null
          continue
        }
        if (c === '"' || c === '`') {
          quote = c
          continue
        }
        if (c === '/' && line[i + 1] === '/') return line.slice(0, i)
      }
      return line
    })
    .join('\n')
}

/** 常量名 -> 字符串值（同时吃 `X T = "v"` 与 `X = "v"` 两种写法）。 */
function constStrings(src) {
  const map = new Map()
  for (const m of src.matchAll(/^\s*(\w+)\s+[A-Za-z]\w*\s*=\s*"([^"]*)"/gm)) map.set(m[1], m[2])
  for (const m of src.matchAll(/^\s*(\w+)\s*=\s*"([^"]*)"/gm)) if (!map.has(m[1])) map.set(m[1], m[2])
  return map
}

/** 取出 `header ... {` 到紧随其后的 `\n}` 之间的正文。 */
function blockBody(src, header) {
  const i = src.indexOf(header)
  if (i < 0) throw new Error(`未找到代码块: ${header}`)
  const open = src.indexOf('{', i)
  const close = src.indexOf('\n}', open)
  if (open < 0 || close < 0) throw new Error(`代码块未闭合: ${header}`)
  return src.slice(open + 1, close)
}

/** `map[T]bool{ A: true, B: true }` -> 按声明顺序的键名。 */
function boolMapKeys(src, header) {
  return [...blockBody(src, header).matchAll(/^\s*(\w+):\s*true,/gm)].map((m) => m[1])
}

/** `map[T][]T{ A: {B, C}, ... }` -> Map<键名, 值名数组>。 */
function sliceMap(src, header) {
  const out = new Map()
  for (const m of blockBody(src, header).matchAll(/^\s*(\w+):\s*\{([^}]*)\}/gm)) {
    out.set(
      m[1],
      m[2]
        .split(',')
        .map((s) => s.trim())
        .filter(Boolean),
    )
  }
  return out
}

function resolveNames(names, constMap, where) {
  return names.map((n) => {
    const v = constMap.get(n)
    if (v === undefined) throw new Error(`${where}: 常量 ${n} 在 Go 源码里找不到对应字符串值`)
    return v
  })
}

const tsStr = (s) => JSON.stringify(s)
const tsArr = (arr) => `[${arr.map(tsStr).join(', ')}] as const`

/** 生成产物文本（纯函数，供生成与校验共用——校验必须与生成走同一条路径）。 */
export function generate() {
  // 多文件拼成一个源串：块的边界不会跨文件，拼接是安全的。
  const model = GO_SOURCES.map((p) => stripComments(readFileSync(p, 'utf8'))).join('\n')
  const capSrc = stripComments(readFileSync(CAP_GO, 'utf8'))
  const mc = constStrings(model)
  const cc = constStrings(capSrc)

  const runtimes = resolveNames(boolMapKeys(model, 'var KnownRuntimes = map[Runtime]bool'), mc, 'KnownRuntimes')
  const implemented = resolveNames(
    boolMapKeys(model, 'var ImplementedRuntimes = map[Runtime]bool'),
    mc,
    'ImplementedRuntimes',
  )
  const versionStates = resolveNames(boolMapKeys(model, 'var ValidStates = map[ToolVersionState]bool'), mc, 'ValidStates')
  const hookStages = resolveNames(boolMapKeys(model, 'var KnownHookStages = map[string]bool'), mc, 'KnownHookStages')
  const flowLevelStages = resolveNames(boolMapKeys(model, 'var FlowLevelStages = map[string]bool'), mc, 'FlowLevelStages')
  const probeKinds = resolveNames(boolMapKeys(model, 'var KnownProbeKinds = map[string]bool'), mc, 'KnownProbeKinds')
  const stepModes = resolveNames(['ModeOnce', 'ModeService'], mc, 'StepMode')
  const capabilities = resolveNames(
    ['PrimHTTP', 'PrimCall', 'PrimDB', 'PrimSecret', 'PrimEvent', 'PrimSubscribe'],
    cc,
    'cap.Primitive',
  )

  const transitions = {}
  for (const [k, vals] of sliceMap(model, 'var VersionTransitions = map[ToolVersionState][]ToolVersionState')) {
    const from = mc.get(k)
    if (from === undefined) throw new Error(`VersionTransitions: 常量 ${k} 无字符串值`)
    transitions[from] = resolveNames(vals, mc, 'VersionTransitions')
  }

  return `// Code generated by scripts/gen-enums.mjs from ${GO_SOURCES.map((p) => relative(REPO_ROOT, p).replace(/\\/g, '/')).join(' + ')}. DO NOT EDIT.
//
// 本文件是内核「合法取值集合」在前端的只读投影（红线 6 单一真相源：内核是唯一真相）。
// 改了 Go 里的枚举就必须重跑 \`npm run gen:enums\`，否则 \`npm run check:contract\` 直接失败。

export const RUNTIMES = ${tsArr(runtimes)}
export const IMPLEMENTED_RUNTIMES = ${tsArr(implemented)}

export const VERSION_STATES = ${tsArr(versionStates)}

export const VERSION_TRANSITIONS: Record<string, readonly string[]> = {
${Object.entries(transitions)
  .map(([k, v]) => `  ${tsStr(k)}: ${tsArr(v)},`)
  .join('\n')}
}

export const HOOK_STAGES = ${tsArr(hookStages)}
export const FLOW_LEVEL_STAGES = ${tsArr(flowLevelStages)}

export const PROBE_KINDS = ${tsArr(probeKinds)}
export const STEP_MODES = ${tsArr(stepModes)}

export const BUILTIN_CAPABILITIES = ${tsArr(capabilities)}

/** 生成时读到的源路径（排障用：产物与源不一致时先看这里）。 */
export const GENERATED_FROM = ${tsStr(GO_SOURCES.map((p) => relative(REPO_ROOT, p).replace(/\\/g, '/')).join(' + '))}
`
}

export function writeGenerated() {
  const text = generate()
  mkdirSync(dirname(OUT_FILE), { recursive: true })
  writeFileSync(OUT_FILE, text, 'utf8')
  return OUT_FILE
}

// 作为脚本直接运行时执行生成。
if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  const out = writeGenerated()
  console.log(`已生成 ${out}`)
}
